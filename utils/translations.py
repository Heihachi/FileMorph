def tr(language: str, key: str, **kwargs) -> str:
    text = TRANSLATIONS.get(language, TRANSLATIONS["ru"]).get(key, key)
    if kwargs:
        try:
            return text.format(**kwargs)
        except Exception:
            return text
    return text